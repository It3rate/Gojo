"""Capture a compact, deterministic display of the 36 verified church proposals.

The generated bytes are a visual publication, not a replacement for the evidence
and native archives in the source dataset. Run with --dataset PATH; --check
compares the publication with a fresh capture without changing files.
"""
from __future__ import annotations

import argparse
import gzip
import hashlib
import json
from pathlib import Path
import zlib


OUT = Path(__file__).resolve().parents[3] / "experiments/quickDraw/results/church-cleanup/public"
ROLES = ("ground", "building", "tower", "roof", "cross", "door", "window")
FINGERPRINT = "77496dbf16acef756bbef207177e9ec481c0bac4a5354b116881417efabfad60"
POLICY = "church-shape-cleanup.v3"
SCALE = 1  # One display unit; the authoritative geometry stays in the dataset.


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def inside(root: Path, relative: str) -> Path:
    path = (root / relative).resolve()
    if not path.is_relative_to(root):
        raise ValueError(f"Dataset path escapes its root: {relative}")
    return path


def flat(points: list[list[float]]) -> list[int]:
    return [round(value * SCALE) for point in points for value in point]


def capture(root: Path) -> bytes:
    folder = root / "church" if (root / "church/manifest.json").is_file() else root
    folder = folder.resolve()
    manifest = json.loads((folder / "manifest.json").read_text(encoding="utf-8"))
    if manifest.get("analysisFingerprint") != FINGERPRINT:
        raise ValueError("This is not the reviewed 36-drawing analysis checkpoint")
    if manifest.get("lastRun", {}).get("storedRecords") != 36 or manifest["lastRun"].get("storedErrors") != 0:
        raise ValueError("Expected 36 successful records and no conversion errors")
    rows = [json.loads(line) for line in (folder / "index.ndjson").read_text(encoding="utf-8").splitlines() if line]
    if len(rows) != 36 or len({row["keyId"] for row in rows}) != 36:
        raise ValueError("The selected drawing set must contain 36 unique source IDs")
    drawings = []
    for number, row in enumerate(rows, 1):
        if row["status"] != "ok" or row["analysisFingerprint"] != FINGERPRINT:
            raise ValueError(f"Unverified analysis row {number}")
        if row["nativeSummary"]["nativeRestoreVerified"] is not True or row["nativeSummary"]["authoredShapeRefinementSaved"] is not True:
            raise ValueError(f"Missing restored shape refinement in row {number}")
        for path_key, hash_key in (("evidencePath", "evidenceSha256"), ("nativePath", "nativeSha256")):
            if digest(inside(folder, row[path_key])) != row[hash_key]:
                raise ValueError(f"Changed source archive in row {number}: {path_key}")
        with gzip.open(inside(folder, row["evidencePath"]), "rt", encoding="utf-8") as stream:
            packet = json.load(stream)
        if packet["source"]["key_id"] != row["keyId"] or packet["cleanup"]["policy"]["version"] != POLICY:
            raise ValueError(f"Wrong source identity or cleanup policy in row {number}")
        strokes = [flat(stroke["points"]) for stroke in packet["observation"]["strokes"]]
        parts = []
        for part in packet["cleanup"]["parts"]:
            if part["role"] not in ROLES:
                raise ValueError(f"Unexpected part role in row {number}: {part['role']}")
            geometry = part["geometry"]
            shown = geometry.get("displaySegments", range(len(geometry["segments"])))
            segments = [index for selected in shown for index in geometry["segments"][selected]]
            fill = geometry.get("fillIndices") or []
            if segments or fill:
                parts.append([ROLES.index(part["role"]), int(part["status"] == "prior-only"),
                              part["shape"], flat(geometry["points"]), segments, fill])
        drawings.append([number, row["keyId"], strokes, parts])
    payload = {"schema": "gojo.quickdraw.church-cleanup-display.v1", "scale": SCALE,
               "roles": ROLES, "drawings": drawings}
    plain = json.dumps(payload, separators=(",", ":"), ensure_ascii=False).encode("utf-8")
    return zlib.compress(plain, level=9)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = capture(args.dataset)
    destination = OUT / "data.bin"
    if args.check:
        if not destination.is_file() or destination.read_bytes() != data:
            raise ValueError("Published visual capture is missing or stale")
    else:
        OUT.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(data)
    print(f"{len(data)} bytes; 36 drawings; {POLICY}; {'checked' if args.check else 'captured'}")


if __name__ == "__main__":
    main()
