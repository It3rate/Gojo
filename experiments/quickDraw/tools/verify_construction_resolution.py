"""Audit finite construction versions against original artwork and native replay.

This reader deliberately does not import the coarsening implementation. Numeric
recipes are evaluated by the independent Fraction reader; the original source
supplies identity, ordering and the scope of authored symmetry/repetition claims.
No expected-coordinate table generated by the converter supplies the answers.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from verify_construction_series import (Audit, VerificationError, canonical_sha256,
                                        evaluate, load_sources, read_lines, verify_inventory)


def verify_native(program, run, audit):
    """Check every restored rung against independently evaluated instructions."""
    audit.expect(run["id"], program["id"], "restored program identity")
    audit.expect(run["nativeRestoreVerified"], True, "native restoration verified")
    audit.expect(run["nativeReplayVerified"], True, "native replay verified")
    audit.expect(run["viewBox"], program["viewBox"], "presentation frame retained")
    audit.expect(len(run["rungs"]), len(program["rungs"]), "every rung restored")
    values, dependencies, rounding = evaluate(program, audit)
    sites = {row["id"]: row for row in program["sites"]}
    edges = {row["id"]: row for row in program["edges"]}
    audit.expect(len(edges), len(program["edges"]), "edge identities unique")
    for key, edge in edges.items():
        audit.require(0 <= edge["at"] < len(program["rungs"]), f"{key} available rung")
        audit.require(2 <= len(edge["controls"]) <= 4, f"{key} supported ordered controls")
        audit.require(all(control in sites for control in edge["controls"]), f"{key} existing control sites")
        audit.require(all(sites[control]["at"] <= edge["at"] for control in edge["controls"]),
                      f"{key} control availability")
    previous, seen = [], set()
    for index, (plan, rung) in enumerate(zip(program["rungs"], run["rungs"])):
        audit.expect(rung["id"], plan["id"], "rung identity")
        audit.expect(rung["verifiedNativeRestore"], True, "rung restoration verified")
        audit.expect(rung["verifiedNativeReplay"], True, "rung replay verified")
        available = [row["id"] for row in program["sites"] if row["at"] <= index]
        audit.expect([row["id"] for row in rung["sites"]], available, "ordered available site inventory")
        for site in rung["sites"]:
            audit.expect([site["x"], site["y"]], values[site["id"]], "independent affine site position")
            audit.expect(set(site["dependencies"]), dependencies[site["id"]], "native causal dependencies")
            audit.expect(site["at"], sites[site["id"]]["at"], "site introduction rung")
        for scope in ("visible", "guides", "selected", "introduced"):
            audit.expect(len(set(plan[scope])), len(plan[scope]), f"unique {scope} scope")
            audit.require(set(plan[scope]) <= edges.keys(), f"known {scope} edges")
        audit.expect(set(plan["visible"]) & set(plan["guides"]), set(), "result and guide scope separate")
        audit.expect(set(plan["selected"]), set(previous) - set(plan["visible"]), "explicit retired edges")
        introduced = {key for key, edge in edges.items() if edge["at"] == index}
        audit.expect(set(plan["introduced"]), introduced, "complete edge introduction")
        seen.update(introduced)
        audit.require(set(plan["visible"] + plan["guides"]) <= seen, "no forward displayed edges")
        audit.expect([edge["id"] for edge in rung["edges"] if not edge["guide"]], plan["visible"],
                     "native visible edge order")
        audit.expect([edge["id"] for edge in rung["edges"] if edge["guide"]], plan["guides"],
                     "native guide edge order")
        for edge in rung["edges"]:
            instruction = edges[edge["id"]]
            controls = instruction["controls"]
            audit.expect(edge["controlSiteIds"], controls, "native control identity and order")
            audit.expect(edge["controls"], [values[key] for key in controls], "native control geometry")
            audit.expect(edge["from"], controls[0], "native start identity")
            audit.expect(edge["to"], controls[-1], "native end identity")
            audit.expect(edge["at"], instruction["at"], "native edge introduction rung")
            audit.expect(edge["introduced"], edge["id"] in plan["introduced"], "native introduction read")
        previous = plan["visible"]
    return values, dependencies, rounding


def verify_axis_order(original, actual, audit):
    """A monotone landmark read preserves equality without welding identities."""
    count = 0
    for axis in (0, 1):
        groups = {}
        for key, point in original.items():
            groups.setdefault(point[axis], []).append(key)
        previous = None
        for coordinate in sorted(groups):
            keys = groups[coordinate]
            positions = {actual[key][axis] for key in keys}
            audit.expect(len(positions), 1, "original aligned endpoint coordinates stay aligned")
            position = next(iter(positions))
            if previous is not None:
                audit.require(previous < position, "strict endpoint coordinate order stays distinct")
                count += 1
            previous = position
            count += len(keys) - 1
    return count


def verify_correspondences(source, controls, audit):
    """Read only authored paired controls, allowing their axis/offset to move."""
    claims = []
    for claim in source.get("correspondences", []):
        flags = claim.get("reversed", [False] * len(claim["source"]))
        audit.expect(len(claim["source"]), len(claim["target"]), "source correspondence arity")
        audit.expect(len(flags), len(claim["source"]), "source reversal arity")
        pairs = [(a, b, reverse) for a, b, reverse in zip(claim["source"], claim["target"], flags)
                 if a in controls and b in controls]
        if not pairs:
            continue
        witnesses = []
        for a, b, reverse in pairs:
            first, second = controls[a], controls[b][::-1] if reverse else controls[b]
            audit.expect(len(first), len(second), "corresponding curve degrees")
            for p, q in zip(first, second):
                if claim["kind"] == "mirror":
                    axis = claim["axis"]
                    audit.expect(axis[0][0], axis[1][0], "authored mirror has supported vertical basis")
                    audit.expect(p[1], q[1], "mirror paired controls share their vertical coordinate")
                    witnesses.append(p[0] + q[0])
                elif claim["kind"] == "repeat":
                    witnesses.append((q[0] - p[0], q[1] - p[1]))
                else:
                    raise VerificationError(f"Unknown source correspondence: {claim['kind']}")
        audit.expect(len(set(witnesses)), 1, f"{claim['kind']} paired controls share one transform")
        witness = witnesses[0]
        claims.append({"id": claim["id"], "kind": claim["kind"], "pairs": len(pairs),
                       "scope": "complete" if len(pairs) == len(claim["source"]) else "selected-pairs-only",
                       "status": "satisfied", "axisTwiceX" if claim["kind"] == "mirror" else "translation": witness})
    return claims


def verify_source_structure(program, source, values, dependencies, audit, exact=False):
    mapping = program["sourceMapping"]
    audit.expect(mapping["sceneId"], source["id"], "original source scene identity")
    original_digest = program["resolution"]["originalSourceSha256"]
    audit.expect(original_digest, canonical_sha256(source), "independent original source content hash")
    if exact:
        audit.expect(mapping["sourceSha256"], original_digest, "exact version keeps original source digest")
    source_sites = {row["id"]: row for row in source["sites"]}
    source_edges = {row["id"]: row for row in source["edges"]}
    edges = {row["id"]: row for row in program["edges"]}
    site_map, edge_map = mapping["siteMap"], mapping["edgeMap"]
    audit.require(bool(edge_map), "nonempty selected source")
    audit.require(set(edge_map) <= source_edges.keys(), "mapped edges belong to original source")
    audit.expect(mapping["sourceEdgeOrder"], [row["id"] for row in source["edges"] if row["id"] in edge_map],
                 "original edge order remains explicit")
    strokes = [[key for key in stroke["edges"] if key in edge_map] for stroke in source["strokes"]]
    audit.expect(mapping["sourceStrokeOrder"], [stroke for stroke in strokes if stroke], "original stroke scope and order")
    endpoint_ids = {source_edges[key][end] for key in edge_map for end in ("from", "to")}
    audit.expect(set(site_map), endpoint_ids, "complete original endpoint inventory")
    audit.expect(len(set(site_map.values())), len(site_map), "coordinate-equal endpoints cannot be welded")
    audit.expect(len(set(edge_map.values())), len(edge_map), "distinct source edge identities retained")
    audit.require(set(site_map.values()) <= values.keys(), "mapped native sites exist")
    audit.require(set(edge_map.values()) <= edges.keys(), "mapped native edges exist")
    actual_sites = {key: values[target] for key, target in site_map.items()}
    original_sites = {key: [source_sites[key]["x"], source_sites[key]["y"]] for key in site_map}
    controls = {}
    for key, target in edge_map.items():
        edge, original = edges[target], source_edges[key]
        ids = edge["controls"]
        audit.expect(len(ids), len(original["controls"]), "source curve degree retained")
        audit.expect(ids[0], site_map[original["from"]], "source start identity retained")
        audit.expect(ids[-1], site_map[original["to"]], "source end identity retained")
        controls[key] = [values[control] for control in ids]
        if exact:
            audit.expect(controls[key], original["controls"], "exact baseline matches independent original controls")
        earlier = {control for plan in program["rungs"][:edge["at"]]
                   for edge_id in plan["visible"] for control in edges[edge_id]["controls"]}
        ancestors, pending = set(), list(ids)
        while pending:
            control = pending.pop()
            if control not in ancestors:
                ancestors.add(control)
                pending.extend(dependencies[control])
        audit.require(bool(ancestors & earlier), "source edge consumes actual earlier visible guide controls")
    audit.expect(set(program["rungs"][-1]["visible"]), set(edge_map.values()), "complete final source edge inventory")
    # Converter tables are checked against instructions, never used as their oracle.
    audit.expect(mapping["expectedSites"], actual_sites, "declared coarse positions agree with native program")
    audit.expect(mapping["expectedControls"], controls, "declared coarse controls agree with native program")
    order_checks = verify_axis_order(original_sites, actual_sites, audit)
    claims = verify_correspondences(source, controls, audit)
    regions = []
    for region in source.get("regions", []):
        if not all(row["edge"] in edge_map for row in region["boundary"]):
            continue
        ends = []
        for reference in region["boundary"]:
            ids = edges[edge_map[reference["edge"]]]["controls"]
            pair = [ids[0], ids[-1]]
            ends.append(pair if reference["forward"] else pair[::-1])
        audit.require(bool(ends), "selected region has a boundary")
        audit.require(all(a[1] == b[0] for a, b in zip(ends, ends[1:] + ends[:1])),
                      "region cycle stays closed by actual shared endpoint identity")
        regions.append(region["id"])
    scopes = {}
    for kind in ("objects", "groups"):
        scopes[kind] = [{"id": row["id"], "edges": [edge_map[key] for key in row["edges"] if key in edge_map]}
                        for row in source.get(kind, []) if any(key in edge_map for key in row["edges"])]
    changed = sum(controls[key] != source_edges[key]["controls"] for key in edge_map)
    displacements = [abs(p[axis] - q[axis]) for key in controls
                     for p, q in zip(controls[key], source_edges[key]["controls"]) for axis in (0, 1)]
    return {"sourceSites": len(site_map), "sourceEdges": len(edge_map), "sourceObjects": len(scopes["objects"]),
            "sourceGroups": len(scopes["groups"]), "closedRegions": len(regions), "endpointOrderChecks": order_checks,
            "correspondences": claims, "sourceScopes": scopes, "changedSourceEdges": changed,
            "maxControlAxisDisplacement": max(displacements, default=0), "originalSourceSha256": original_digest}


def verify_connected_reads(program, source, dependencies, audit):
    """Check claimed coupling against real ordered affine instructions."""
    sites = {row["id"]: row for row in program["sites"]}
    order = {row["id"]: index for index, row in enumerate(program["sites"])}
    edges = {row["id"]: row for row in program["edges"]}
    source_edges = {row["id"]: row for row in source["edges"]}
    controls = {key: edges[target]["controls"] for key, target in program["sourceMapping"]["edgeMap"].items()}
    original_points = {}
    for key, ids in controls.items():
        for site_id, point in zip(ids, source_edges[key]["controls"]):
            if site_id in original_points:
                audit.expect(original_points[site_id], point, "shared control retains one original position")
            original_points[site_id] = point
    mirror_pairs, repeat_pairs = set(), set()
    for claim in source.get("correspondences", []):
        if claim["kind"] not in ("mirror", "repeat"):
            continue
        for first, second, reverse in zip(claim["source"], claim["target"], claim["reversed"]):
            if first not in controls or second not in controls:
                continue
            targets = controls[second][::-1] if reverse else controls[second]
            for a, b in zip(controls[first], targets):
                if claim["kind"] == "mirror":
                    mirror_pairs.update(((a, b), (b, a)))
                else:
                    repeat_pairs.add((a, b))
    counts = {"alignment": 0, "reflection": 0, "axis": 0, "translation": 0}
    seen = set()
    for binding in program.get("resolutionBindings", []):
        target, axis, origin = binding["site"], binding["axis"], binding["source"]
        audit.require(target in original_points, "connected read target is a selected source control")
        audit.require(axis in ("x", "y"), "connected read has an axis")
        audit.require((target, axis) not in seen, "connected read owns one coordinate instruction")
        seen.add((target, axis))
        audit.require(origin in sites and order[origin] < order[target], "connected read consumes an earlier site")
        audit.require(origin in dependencies[target], "connected read appears in actual native dependencies")
        expression = sites[target][axis]
        audit.require(isinstance(expression, dict), "connected read is an affine relation")
        kind = binding["read"]
        audit.require(kind in counts, "supported connected read")
        if kind == "reflection":
            anchor = binding["axisSite"]
            audit.require(axis == "x" and (target, origin) in mirror_pairs,
                          "reflection consumes an original declared paired control")
            audit.require(anchor in sites and order[anchor] < order[target], "reflection consumes an earlier axis site")
            audit.expect([expression["from"], expression["to"], expression.get("origin", expression["from"]),
                          expression["numerator"], expression["denominator"]],
                         [origin, anchor, anchor, 1, 1], "actual native reflection relation")
            audit.require(anchor in dependencies[target], "reflection axis is a native dependency")
        elif kind == "translation":
            audit.require((origin, target) in repeat_pairs, "translation consumes an original declared paired control")
            audit.expect(expression.get("origin", expression["from"]), origin, "actual native translated origin")
            audit.require(all(order[expression[key]] < order[target] for key in ("from", "to")),
                          "translation consumes an earlier measurement frame")
        else:
            audit.expect([expression["from"], expression["to"], expression.get("origin", expression["from"]),
                          expression["numerator"]], [origin, origin, origin, 0], "actual native coordinate-copy relation")
            if kind == "alignment":
                audit.require(origin in original_points, "alignment consumes an actual source control")
                dimension = ("x", "y").index(axis)
                audit.expect(original_points[target][dimension], original_points[origin][dimension],
                             "alignment preserves an original equal-coordinate premise")
            else:
                audit.require(axis == "x" and (target, target) in mirror_pairs,
                              "axis copy is an original self-mirror control")
                audit.expect(binding["axisSite"], origin, "self-mirror consumes its axis site")
        counts[kind] += 1
    return counts


def verify_program(program, run, source):
    audit = Audit(program["id"])
    resolution = program["resolution"]
    audit.expect(program["id"], resolution["baseId"] + "--" + resolution["levelId"], "resolution program identity")
    values, dependencies, rounding = verify_native(program, run, audit)
    summary = verify_source_structure(program, source, values, dependencies, audit,
                                      exact=resolution["levelId"] == "exact")
    connected = verify_connected_reads(program, source, dependencies, audit)
    return {"id": program["id"], "baseId": resolution["baseId"], "levelId": resolution["levelId"],
            "sceneId": source["id"], "checks": audit.checks, "rungs": len(program["rungs"]),
            "finiteCoordinateRemainders": len(rounding), "connectedReads": connected,
            "status": "satisfied", **summary}


def verify_inventory_levels(programs, runs, manifest, sources):
    audit = Audit("resolution inventory")
    levels = [row["id"] for row in manifest["levels"]]
    audit.expect(len(levels), len(set(levels)), "unique resolution levels")
    audit.require("exact" in levels, "exact baseline available")
    by_id = {program["id"]: program for program in programs}
    audit.expect(len(by_id), len(programs), "unique construction program identities")
    audit.expect(set(runs), set(by_id), "one restored native read for every program")
    manifest_rows = {row["id"]: row for row in manifest["programs"]}
    audit.expect(len(manifest_rows), len(manifest["programs"]), "unique manifest identities")
    audit.expect(set(manifest_rows), set(by_id), "manifest covers exactly all programs")
    baselines = {p["resolution"]["baseId"]: p for p in programs if p["resolution"]["levelId"] == "exact"}
    expected_pairs = {(base, level) for base in baselines for level in levels}
    actual_pairs = [(p["resolution"]["baseId"], p["resolution"]["levelId"]) for p in programs]
    audit.expect(len(actual_pairs), len(set(actual_pairs)), "one program per source and resolution")
    audit.expect(set(actual_pairs), expected_pairs, "every source has every resolution")
    for p in programs:
        resolution = p["resolution"]
        row = manifest_rows[p["id"]]
        audit.expect([row["baseId"], row["levelId"]], [resolution["baseId"], resolution["levelId"]],
                     "manifest resolution matches source program")
        baseline = baselines[resolution["baseId"]]
        for key in ("sceneId", "sourceEdgeOrder", "sourceStrokeOrder", "siteMap", "edgeMap"):
            audit.expect(p["sourceMapping"][key], baseline["sourceMapping"][key], f"stable source correspondence {key}")
        audit.expect(p["edges"], baseline["edges"], "same edge identities, control identities and introduction order")
        for key in ("visible", "guides", "selected", "introduced"):
            audit.expect([rung[key] for rung in p["rungs"]], [rung[key] for rung in baseline["rungs"]],
                         f"same construction rung {key} scope")
    audit.checks += verify_inventory(list(baselines.values()), sources)
    return audit.checks


def verify(root, sources=None, write_transitions=True):
    sources = load_sources() if sources is None else sources
    programs = read_lines(root / "programs.ndjson")
    native_rows = read_lines(root / "native" / "inspector.ndjson")
    runs = {run["id"]: run for run in native_rows}
    if len(runs) != len(native_rows):
        raise VerificationError("Native inspector repeats a program identity")
    manifest = json.loads((root / "resolution-manifest.json").read_text(encoding="utf-8"))
    inventory = verify_inventory_levels(programs, runs, manifest, sources)
    summaries = [verify_program(p, runs[p["id"]], sources[p["sourceMapping"]["sceneId"]]) for p in programs]
    transitions = []
    if write_transitions:
        from verify_construction_ladders import transition
        for p in programs:
            for index in range(len(p["rungs"]) - 1):
                row = transition(p, runs[p["id"]], index)
                row["provenance"]["resolutionLevel"] = p["resolution"]["levelId"]
                row["provenance"]["resolutionBaseId"] = p["resolution"]["baseId"]
                if row["provenance"]["splitUnit"] != p["sourceMapping"]["sceneId"]:
                    raise VerificationError("Resolution versions must remain in one source-scene split")
                transitions.append(row)
        (root / "transitions.ndjson").write_text("".join(json.dumps(row, separators=(",", ":")) + "\n"
                                                        for row in transitions), encoding="utf-8")
    levels = []
    for level in manifest["levels"]:
        selected = [row for row in summaries if row["levelId"] == level["id"]]
        levels.append({"id": level["id"], "programs": len(selected),
                       "changedPrograms": sum(row["changedSourceEdges"] > 0 for row in selected),
                       "changedSourceEdges": sum(row["changedSourceEdges"] for row in selected),
                       "maxControlAxisDisplacement": max(row["maxControlAxisDisplacement"] for row in selected)})
    report = {"schema": "gojo.construction-resolution-verification.v1", "passed": True,
              "programs": len(summaries), "levels": levels, "checks": inventory + sum(row["checks"] for row in summaries),
              "rungs": sum(row["rungs"] for row in summaries), "transitions": len(transitions),
              "sourceScenes": len({row["sceneId"] for row in summaries}), "trainedModel": False,
              "sourceSha256": hashlib.sha256((root / "programs.ndjson").read_bytes()).hexdigest(),
              "nativeInspectorSha256": hashlib.sha256((root / "native" / "inspector.ndjson").read_bytes()).hexdigest(),
              "auditScriptSha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
              "checksPerformed": ["independent rational evaluation and native replay for every construction rung",
                                  "original source identity, degree, acquisition order and endpoint incidence",
                                  "strict endpoint axis order and equal-coordinate alignment without identity welding",
                                  "original declared mirror and translation claims on paired ordered curve controls",
                                  "shared-site region closure, object/group membership and stable per-level inventories",
                                  "exact baseline control parity and source-scene grouping across resolutions"],
              "limits": ["These are authored numeric recipes and coarse numeric reads, not learned or prenumeric concepts.",
                         "Mirror and repeat checks cover original authored paired scopes, not all apparent symmetry.",
                         "Endpoint order and closed boundary identity do not prove arbitrary curve containment or absence of new intersections.",
                         "Original object/group membership is an independently retained scope; it does not establish recognized object semantics.",
                         "The coarse programs are checked independently of converter expected-coordinate tables."],
              "runs": summaries}
    (root / "resolution-verification.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({key: report[key] for key in ("passed", "programs", "checks", "rungs", "transitions")}))
    return report


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    verify(parser.parse_args().root)
