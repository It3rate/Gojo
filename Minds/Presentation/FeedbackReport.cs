using System.Text.Json;
using Gojo.Core;
using Minds.TwoSpace;
using static Minds.TwoSpace.Graph;

namespace Minds.Presentation;

/// <summary>One-way display adapter. Decimal chart coordinates never feed participant actions.</summary>
public static class FeedbackReport
{
    private static readonly string[] Measures = ["a", "b", "mean", "gap", "da", "db", "movement", "meanChange", "aReferenceGap", "bReferenceGap"];
    public sealed record DisplayNumber(long Numerator, long Denominator, string Text, double Value);

    public static void Write(string directory, IReadOnlyList<FeedbackRun> runs)
    {
        Directory.CreateDirectory(directory);
        var data = runs.Select(run => new {
            run.Case.Id, run.Case.Name, run.Case.Description,
            run.Case.ResponseDenominator, run.Case.FreshPublication, run.Case.UseReference,
            EndReason = "Six observed rounds; no claim that the system has stopped.",
            Events = run.Events.Select((e, index) => new {
                Index = index, e.Description, e.Applied, e.AAttempts, e.BAttempts,
                Measures = Values(e.Observation),
                APlan = Plan(F(e.Evidence)[1]), BPlan = Plan(F(e.Evidence)[2]),
                ATension = Number(F(e.Evidence)[3]), BTension = Number(F(e.Evidence)[4]),
                PublishedA = Publication(e.PublishedA), PublishedB = Publication(e.PublishedB)
            }),
            Rounds = run.Rounds.Select((r, index) => new {
                Index = index, r.Description, r.EventIndex, Measures = Values(r.Observation)
            })
        });
        var json = JsonSerializer.Serialize(data, new JsonSerializerOptions {
            PropertyNamingPolicy = JsonNamingPolicy.CamelCase, WriteIndented = true
        });
        File.WriteAllText(Path.Combine(directory, "trace.json"), json);
        var template = File.ReadAllText(Path.Combine(AppContext.BaseDirectory, "Presentation", "two-space.html"));
        File.WriteAllText(Path.Combine(directory, "index.html"), template.Replace("__TRACE_JSON__", json));
        var rows = runs.Select(run => {
            var last = Values(run.Rounds[^1].Observation);
            return $"| {run.Case.Name} | {last["a"].Text} | {last["b"].Text} | {last["mean"].Text} | {last["gap"].Text} | {last["movement"].Text} |";
        });
        File.WriteAllText(Path.Combine(directory, "Results.md"),
            "# Two-space feedback: exploratory observation\n\n" +
            "Generated by `dotnet run --project Minds -- <output-directory>`. Values below are read from Gojo observer structures. " +
            "All five conditions use fresh worlds and the same authored fixture. This is a six-round observation window, not a convergence test.\n\n" +
            "| Condition | A | B in A units | Average | B minus A | Movement in last round |\n" +
            "| --- | ---: | ---: | ---: | ---: | ---: |\n" + string.Join("\n", rows) + "\n\n" +
            "Movement is abs(change in A) + abs(change in B), a measured change in estimates, not physical energy or CPU work. " +
            "The plot also exposes the temporary changes between the two applications.\n\n" +
            "The local reference values both read as 2 in the comparison unit. Reference mismatches remain available even while peer mismatch is zero. " +
            "The reference condition deliberately selects those existing observations in round 3; it does not discover that selection.\n\n" +
            "Response, comparison, receipt, and application use existing LocalCalibration readers. " +
            "Average, mismatch and movement use BoundedQuantity observations and calibrated composition. " +
            "The host selects schedules and response fractions. The browser only displays captured results.\n\n" +
            "Retained fractional requests are plan residue; they are not automatically carrier tension. " +
            "Unknown source reliability remains unknown. Automatic idling, response-policy discovery, and replacement by a learned equation are future work.\n\n" +
            "Open [the step viewer](index.html), inspect [the exported observations](trace.json), or read " +
            "[the selected setup](../../docs/TwoSpaceExploration.md). These diagnostic files are not a complete restorable world.\n");
    }

    private static Dictionary<string, DisplayNumber> Values(Relation observation) =>
        Measures.Select((name, index) => (name, value: Number(PairObserver.Scalar(R(F(observation)[index])))))
            .ToDictionary(pair => pair.name, pair => pair.value);

    private static object? Plan(IElement element)
    {
        if (element is not Relation plan || !plan.TryReadOrderedGroup(out var p) || p.Length != 5 ||
            p[2] is not Relation result || !result.TryReadOrderedGroup(out var v) || v.Length != 4 ||
            p[3] is not Relation residue || !residue.TryReadOrderedGroup(out var rem) || rem.Length != 2) return null;
        return new { Requested = Number(v[0]), Whole = Number(v[1]), Remainder = Number(rem[0]) };
    }

    private static DisplayNumber? Publication(Relation? message) =>
        message is null ? null : Number(F(F(message)[0])[2]);

    private static DisplayNumber Number(IElement scalar)
    {
        Require(ProjectionResidue.TryRead(scalar, out _, out var n, out var d), "display scalar");
        return new DisplayNumber(n, d, d == 1 ? n.ToString(System.Globalization.CultureInfo.InvariantCulture) : $"{n}/{d}", (double)n / d);
    }
}
